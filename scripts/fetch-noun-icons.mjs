#!/usr/bin/env node
/*
  Fetch Noun Project icons for the landing page.

  Run from the repo root on your own computer (Node 18+, no npm install needed):

    Windows CMD:
      set NOUN_KEY=your_key
      set NOUN_SECRET=your_secret
      node scripts/fetch-noun-icons.mjs

    macOS / Linux:
      NOUN_KEY=your_key NOUN_SECRET=your_secret node scripts/fetch-noun-icons.mjs

  It searches one icon per term below, downloads each PNG into public/noun/<key>.png
  (self-hosted, no hotlinking) and writes
  src/pages/landing/noun-icons.ts  ->  NOUN_ICONS = { key: { id, url: '/noun/<key>.png', attribution } }
  The landing page (NounGlyph) and the app icons (ZIcon) use these automatically and
  fall back to the built-in line icons for any key that is missing.

  The app's semantic icons come from src/components/icons/icon-terms.json and are
  stored under the key `ui-<name>` (for example ui-insight).

  Keys are read from environment variables only. Never commit them.
*/
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const KEY = process.env.NOUN_KEY;
const SECRET = process.env.NOUN_SECRET;
if (!KEY || !SECRET) {
  console.error('Set NOUN_KEY and NOUN_SECRET environment variables first.');
  process.exit(1);
}

// key used in the code  ->  search term on The Noun Project
const TERMS = {
  scheduler: 'calendar schedule',
  dashboard: 'analytics dashboard',
  spreadsheet: 'spreadsheet',
  chatbot: 'chatbot',
  tracker: 'binoculars',
  inbox: 'inbox',
  diagnosis: 'stethoscope',
  roas: 'decrease chart',
  fatigue: 'low battery',
  scheduling: 'alarm clock',
  competitor: 'radar',
  unified: 'chat bubbles',
  founder: 'rocket',
  freelancer: 'laptop work',
  agency: 'team',
  draft: 'pencil',
  approve: 'approve',
  publish: 'paper plane',
  // Social platforms are NOT fetched: they always use their official logos (SocialIcon).
};

const enc = (s) => encodeURIComponent(s).replace(/[!'()*]/g, (c) => '%' + c.charCodeAt(0).toString(16).toUpperCase());

function signedUrl(base, query) {
  const oauth = {
    oauth_consumer_key: KEY,
    oauth_nonce: crypto.randomBytes(16).toString('hex'),
    oauth_signature_method: 'HMAC-SHA1',
    oauth_timestamp: Math.floor(Date.now() / 1000).toString(),
    oauth_version: '1.0',
  };
  const all = { ...query, ...oauth };
  const paramStr = Object.keys(all).sort().map((k) => `${enc(k)}=${enc(all[k])}`).join('&');
  const baseStr = ['GET', enc(base), enc(paramStr)].join('&');
  const sig = crypto.createHmac('sha1', `${enc(SECRET)}&`).update(baseStr).digest('base64');
  all.oauth_signature = sig;
  return `${base}?${Object.keys(all).sort().map((k) => `${enc(k)}=${enc(all[k])}`).join('&')}`;
}

async function search(term, publicDomain) {
  const q = { query: term, limit: '1', thumbnail_size: '200' };
  if (publicDomain) q.limit_to_public_domain = '1';
  const res = await fetch(signedUrl('https://api.thenounproject.com/v2/icon', q));
  if (!res.ok) throw new Error(`${res.status} ${await res.text()}`);
  const json = await res.json();
  return (json.icons || [])[0];
}

// Semantic app icons (shared with src/components/icons/iconRegistry.ts).
const UI_TERMS = JSON.parse(fs.readFileSync(path.join('src', 'components', 'icons', 'icon-terms.json'), 'utf8'));
for (const [name, def] of Object.entries(UI_TERMS)) TERMS[`ui-${name}`] = def.noun;

const PUBLIC_DIR = path.join('public', 'noun');
fs.mkdirSync(PUBLIC_DIR, { recursive: true });

async function download(url, file) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`download ${res.status} for ${url}`);
  fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
}

const out = {};
for (const [key, term] of Object.entries(TERMS)) {
  try {
    const icon = (await search(term, true)) || (await search(term, false));
    if (!icon) {
      console.log(`- ${key}: no result for "${term}"`);
      continue;
    }
    const remote = icon.thumbnail_url || `https://static.thenounproject.com/png/${icon.id}-200.png`;
    await download(remote, path.join(PUBLIC_DIR, `${key}.png`));
    out[key] = {
      id: String(icon.id),
      url: `/noun/${key}.png`,
      attribution: icon.attribution || '',
    };
    console.log(`+ ${key}: #${icon.id} ${icon.attribution || ''}`);
  } catch (e) {
    console.log(`! ${key}: ${e.message}`);
  }
}

const file = path.join('src', 'pages', 'landing', 'noun-icons.ts');
fs.writeFileSync(
  file,
  '// Generated by scripts/fetch-noun-icons.mjs\n' +
    'export const NOUN_ICONS: Record<string, { id: string; url: string; attribution?: string }> = ' +
    JSON.stringify(out, null, 2) +
    ';\n',
);
console.log(`\nSaved ${Object.keys(out).length} icons to ${file} (images in ${PUBLIC_DIR})`);
console.log('If any icon is not public domain, keep its attribution (shown above) in your site credits.');
console.log('Fetched icons stay hidden until you review public/noun/<key>.png and add the key to src/components/icons/nounApproved.ts.');
